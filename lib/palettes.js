// 把派生值合并进每套配色（原地扩展，保持 22 个手调值不变）
for (const p of PALETTES) {
  const e = EXTRA_DERIVED(p)
  Object.assign(p.light, e.light)
  Object.assign(p.dark, e.dark)
}

export { EXTRA_DERIVED }

